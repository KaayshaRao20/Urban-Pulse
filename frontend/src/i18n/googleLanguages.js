export function getSavedGoogleLang() {
  try {
    // 1. Check googtrans cookie
    const cookies = document.cookie.split(';');
    for (const c of cookies) {
      const trimmed = c.trim();
      if (trimmed.startsWith('googtrans=')) {
        const val = trimmed.split('=')[1]; // e.g. /en/kn or /auto/kn
        if (val) {
          const parts = val.split('/');
          const code = parts[parts.length - 1];
          if (code && code !== 'en') return code;
        }
      }
    }
    // 2. Check localStorage
    const saved = localStorage.getItem('urbanpulse_citizen_lang');
    if (saved) return saved;
  } catch (e) {
    // Fallback
  }
  return 'en';
}

export function applyGoogleTranslate(langCode) {
  try {
    const hostname = window.location.hostname;
    const isLocal = hostname === 'localhost' || hostname === '127.0.0.1';

    if (langCode === 'en') {
      // Clear cookie to restore English
      document.cookie = 'googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=/;';
      document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; domain=${hostname}; path=/;`;
      document.cookie = 'googtrans=/en/en; path=/;';
      document.cookie = `googtrans=/en/en; domain=${hostname}; path=/;`;
      localStorage.setItem('urbanpulse_citizen_lang', 'en');

      const select = document.querySelector('.goog-te-combo');
      if (select) {
        select.value = 'en';
        select.dispatchEvent(new Event('change'));
      }
      return;
    }

    const cookieVal = `/en/${langCode}`;
    document.cookie = `googtrans=${cookieVal}; path=/;`;
    document.cookie = `googtrans=${cookieVal}; domain=${hostname}; path=/;`;
    if (!isLocal && hostname.includes('.')) {
      const rootDomain = '.' + hostname.split('.').slice(-2).join('.');
      document.cookie = `googtrans=${cookieVal}; domain=${rootDomain}; path=/;`;
    }

    localStorage.setItem('urbanpulse_citizen_lang', langCode);

    // Trigger select element if Google Translate has mounted it
    const select = document.querySelector('.goog-te-combo');
    if (select) {
      select.value = langCode;
      select.dispatchEvent(new Event('change'));
    }
  } catch (err) {
    console.warn('Google Translate trigger:', err);
  }
}

export function initGoogleTranslate() {
  if (typeof window === 'undefined') return;

  window.googleTranslateElementInit = function () {
    try {
      if (window.google && window.google.translate) {
        new window.google.translate.TranslateElement(
          {
            pageLanguage: 'en',
            layout: window.google.translate.TranslateElement.InlineLayout.SIMPLE,
            autoDisplay: false
          },
          'google_translate_element'
        );
      }
    } catch (e) {
      console.warn('Google Translate init:', e);
    }
  };

  if (!document.getElementById('google-translate-script')) {
    const script = document.createElement('script');
    script.id = 'google-translate-script';
    script.type = 'text/javascript';
    script.src = 'https://translate.google.com/translate_a/element.js?cb=googleTranslateElementInit';
    script.async = true;
    document.body.appendChild(script);
  } else if (window.google && window.google.translate && !document.querySelector('.goog-te-combo')) {
    try {
      new window.google.translate.TranslateElement(
        {
          pageLanguage: 'en',
          layout: window.google.translate.TranslateElement.InlineLayout.SIMPLE,
          autoDisplay: false
        },
        'google_translate_element'
      );
    } catch (e) {}
  }
}
